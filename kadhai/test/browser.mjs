import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, executablePath: process.env.CHROMIUM_PATH});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.waitForFunction(()=>window.kadhai);
await page.waitForFunction(() => window.kadhai.snapshot().elapsed > 17, null, { timeout: 90000 });
await page.getByRole('button',{name:'Pause',exact:true}).click();
const mature=await page.evaluate(()=>window.kadhai.snapshot());
assert.ok(mature.cells[0].growth>.95);
assert.ok(mature.totalFood>0);
await page.screenshot({path:'assets/kadhai-floating-cells.png'});
const pausedTime=mature.elapsed;
await page.waitForTimeout(250);
assert.equal((await page.evaluate(()=>window.kadhai.snapshot())).elapsed,pausedTime);
await page.getByRole('button',{name:'Show structure'}).click();
assert.equal(await page.getByRole('button',{name:'Hide structure'}).getAttribute('aria-pressed'),'true');
await page.locator('#mutation').fill('70');assert.equal(await page.locator('#mutation-value').textContent(),'70%');
await page.locator('#speed').fill('3');assert.equal(await page.locator('#speed-value').textContent(),'3×');
await page.getByRole('button',{name:'Next generation'}).click();
assert.equal((await page.evaluate(()=>window.kadhai.snapshot())).generation,2);
await page.getByRole('button',{name:'Start a new lineage'}).click();
assert.equal((await page.evaluate(()=>window.kadhai.snapshot())).generation,1);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'assets/kadhai-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.getByRole('button',{name:'Resume',exact:true}).click();
await page.waitForTimeout(500);
assert.ok((await page.evaluate(()=>window.kadhai.snapshot())).elapsed>0);
assert.deepEqual(errors,[]);
console.log(JSON.stringify({browser:'passed',food:mature.totalFood,elapsed:mature.elapsed,growth:mature.cells[0].growth,errors},null,2));
await browser.close();
